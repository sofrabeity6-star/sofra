// يحوّل علامات ? إلى $1..$n (مع تجاهل ما بداخل النصوص '...')
function toPg(sql) {
  let n = 0;
  let out = '';
  let inStr = false;
  for (const ch of sql) {
    if (ch === "'") inStr = !inStr;
    out += !inStr && ch === '?' ? `$${++n}` : ch;
  }
  return out;
}

function sslFor(url) {
  if (process.env.PGSSLMODE === 'disable') return false;
  if (/localhost|127\.0\.0\.1|sslmode=disable/.test(url)) return false;
  return { rejectUnauthorized: false }; // Supabase يتطلب SSL
}

/**
 * يفتح الاتصال ويطبّق الترحيلات.
 * @param {object} o
 * @param {string} o.url  رابط Postgres (DATABASE_URL)
 * @param {string} [o.schema] مخطط بديل عن public (للاختبارات المعزولة)
 */
async function openDb({ url = process.env.DATABASE_URL, schema, max = Number(process.env.PG_POOL_MAX) || 5 } = {}) {
  if (!url) throw new Error('DATABASE_URL غير مضبوط. ضع رابط Postgres من Supabase في ملف .env أو في إعدادات Render.');
  const pool = new Pool({
    connectionString: url,
    ssl: sslFor(url),
    max,
    idleTimeoutMillis: 30000,
    connectionTimeoutMillis: 15000,
    ...(schema ? { options: `-c search_path=${schema}` } : {}),
  });
  pool.on('error', (e) => console.error('[pg] خطأ في اتصال خامل:', e.message));
  const als = new AsyncLocalStorage();

  const runner = () => (als.getStore() || pool);
  async function query(sql, params = []) {
    return runner().query(toPg(sql), params);
  }

  const db = {
    pool,
    schema: schema || 'public',
    query,
    /** صف واحد أو undefined */
    one: async (sql, ...p) => (await query(sql, p)).rows[0],
    /** كل الصفوف */
    all: async (sql, ...p) => (await query(sql, p)).rows,
    /** تنفيذ: يرجع { changes, rows } */
    run: async (sql, ...p) => { const r = await query(sql, p); return { changes: r.rowCount, rows: r.rows, id: r.rows[0] && r.rows[0].id }; },
    /** معاملة. المعاملات المتداخلة تستخدم SAVEPOINT */
    async tx(fn) {
      const cur = als.getStore();
      if (cur) {
        const sp = `sp${++cur.__depth}`;
        await cur.query(`SAVEPOINT ${sp}`);
        try { const r = await fn(); await cur.query(`RELEASE SAVEPOINT ${sp}`); return r; }
        catch (e) { await cur.query(`ROLLBACK TO SAVEPOINT ${sp}`); throw e; }
        finally { cur.__depth -= 1; }
      }
      const client = await pool.connect();
      client.__depth = 0;
      try {
        await client.query('BEGIN');
        const r = await als.run(client, fn);
        await client.query('COMMIT');
        return r;
      } catch (e) {
        try { await client.query('ROLLBACK'); } catch { /* الاتصال مقطوع */ }
        throw e;
      } finally { client.release(); }
    },
    /** يشغّل دالة خارج أي معاملة جارية (لأعمال الخلفية مثل الإشعارات) */
    detached: (fn) => als.exit(fn),
    close: () => pool.end(),
    _settings: null, // ذاكرة مؤقتة للإعدادات (نسخة خادم واحدة)
  };

  await migrate(db);
  return db;
}

async function migrate(db) {
  // قفل حتى لا تتسابق نسختان من الخادم على الترحيل
  await db.tx(async () => {
    await db.query('SELECT pg_advisory_xact_lock(727274)');
    await db.query('CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL)');
    const row = await db.one('SELECT COALESCE(MAX(version),0) AS v FROM schema_migrations');
    for (let v = row.v; v < MIGRATIONS.length; v++) {
      await db.query(MIGRATIONS[v]);
      await db.query('INSERT INTO schema_migrations(version, applied_at) VALUES(?, ?)', [v + 1, new Date().toISOString()]);
    }
  });
}

