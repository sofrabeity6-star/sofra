async function getSettings(db) {
  // ذاكرة مؤقتة قصيرة (15 ثانية) لتقليل الاستعلامات، وتُمسح فوراً عند الحفظ من لوحة الإدارة
  if (db._settings && Date.now() - db._settingsAt < 15000) return { ...db._settings, payment_accounts: [...db._settings.payment_accounts] };
  const out = { ...DEFAULT_SETTINGS };
  for (const r of await db.all('SELECT key, value FROM settings')) {
    try { out[r.key] = JSON.parse(r.value); } catch { /* تجاهل القيم التالفة */ }
  }
  db._settings = out;
  db._settingsAt = Date.now();
  return { ...out, payment_accounts: [...out.payment_accounts] };
}

async function saveSettings(db, patch) {
  await db.tx(async () => {
    for (const [k, v] of Object.entries(patch)) {
      if (k in DEFAULT_SETTINGS) {
        await db.run('INSERT INTO settings(key,value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value', k, JSON.stringify(v));
      }
    }
  });
  db._settings = null;
  return getSettings(db);
}

